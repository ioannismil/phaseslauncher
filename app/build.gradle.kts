android {
    namespace = "com.phaseslauncher"
    compileSdk = 37

    defaultConfig {
        applicationId = "com.phaseslauncher"
        minSdk = 26
        targetSdk = 37
        // Set in gradle.properties, where F-Droid reads them too.
        versionCode = providers.gradleProperty("versionCode").get().toInt()
        versionName = providers.gradleProperty("versionName").get()

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    // The release key, when the environment provides it (CI does, from the repo's secrets).
    val releaseStore = providers.environmentVariable("SIGNING_STORE_FILE").orNull
    signingConfigs {
        if (releaseStore != null) {
            create("release") {
                storeFile = file(releaseStore)
                storePassword = providers.environmentVariable("SIGNING_STORE_PASSWORD").get()
                keyAlias = providers.environmentVariable("SIGNING_KEY_ALIAS").get()
                keyPassword = providers.environmentVariable("SIGNING_KEY_PASSWORD").get()
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            when {
                // For measuring on a device: ./gradlew installRelease -PdebugSignedRelease
                project.hasProperty("debugSignedRelease") -> signingConfig = signingConfigs.getByName("debug")
                releaseStore != null -> signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    // Leave out the dependency list AGP otherwise adds to the signing block, encrypted for
    // Google Play only. F-Droid and IzzyOnDroid reject APKs that carry it.
    dependenciesInfo {
        includeInApk = false
        includeInBundle = false
    }
}

